const pick = <T,>(xs: T[], n: number) => xs[n % xs.length];

export function cannedRoast(b: ScannedBullet, intensity: Intensity): string {
  const top = [...b.flags].sort((a, c) => PRIORITY[c.rule] - PRIORITY[a.rule])[0];
  const rule: RuleId = top?.rule ?? 'no-metric';
  return pick(ROASTS[rule][intensity], b.id);
}

export function ruleTip(rule: RuleId): string {
  return TIPS[rule];
}

export function praiseCard(intensity: Intensity) {
  return {
    original: 'Your resume, which turned out to be fine.',
    roast: pick(PRAISE[intensity], 0),
    tip: 'Nothing major to fix. Double-check your top three bullets still lead with your best results.',
  };
}

export function keepOriginalMock(intensity: Intensity): string {
  return pick(MOCKS[intensity], 0);
}
