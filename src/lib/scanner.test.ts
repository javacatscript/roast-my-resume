import { describe, it, expect } from 'vitest';
import { scanBullet, scanResume } from '@/lib/scanner';

const rules = (text: string) => scanBullet({ id: 0, text, start: 0, end: text.length }).flags.map((f) => f.rule);

describe('scanBullet', () => {
  it.each([
    'Responsible for managing the release process with 3 teams',
    'Helped with onboarding of 12 new hires',
    'Worked on the billing service for 4 clients',
    'Assisted in migrating 20 services to the cloud',
  ])('flags weak phrase in "%s"', (text) => {
    expect(rules(text)).toContain('weak-phrase');
  });

  it('flags a bullet with no metric', () => {
    expect(rules('Improved the checkout flow for customers')).toContain('no-metric');
  });

  it('does not flag a bullet that has a metric', () => {
    expect(rules('Cut load time 42% by lazy-loading images')).not.toContain('no-metric');
  });

  it('treats words like "thousands" as a metric', () => {
    expect(rules('Served thousands of customers during launch week')).not.toContain(
      'no-metric',
    );
  });

  it('flags passive voice', () => {
    expect(rules('Reports were generated by the team weekly for 5 clients')).toContain(
      'passive',
    );
  });

  it('flags a bullet over 220 characters as too long', () => {
    expect(rules(`Built ${'a very detailed thing '.repeat(12)}for 3 clients`)).toContain(
      'too-long',
    );
  });

  it('gives a clean bullet no flags', () => {
    const b = scanBullet({ id: 0, text: 'Cut p95 latency 38% by caching hot queries', start: 0, end: 41 });
    expect(b.flags).toEqual([]);
    expect(b.score).toBe(0);
  });
});

describe('scanResume', () => {
  it('flags repeated opening verbs on the 2nd and 3rd occurrence only', () => {
    const r = scanResume(
      [
        '• Managed the budget of 4 teams',
        '• Managed 6 vendors across 3 regions',
        '• Managed a roster of 12 interns',
      ].join('\n'),
    );
    const has = (i: number) => r.all[i].flags.some((f) => f.rule === 'repeated-verb');
    expect([has(0), has(1), has(2)]).toEqual([false, true, true]);
  });

  it('ranks the bullet with more flags first', () => {
    const r = scanResume(
      [
        '• Improved the checkout flow for customers',
        '• Responsible for reports that were generated by the team',
      ].join('\n'),
    );
    expect(r.flagged[0].text).toMatch(/^Responsible for reports/);
    expect(r.flagged[0].score).toBeGreaterThan(r.flagged[1].score);
  });

  it('caps flagged cards at 8 by default', () => {
    const text = Array.from(
      { length: 12 },
      (_, i) => `• Responsible for project number ${i} across the company`,
    ).join('\n');
    const r = scanResume(text);
    expect(r.all).toHaveLength(12);
    expect(r.flagged).toHaveLength(8);
  });

  it('respects a custom cap', () => {
    const text = Array.from(
      { length: 5 },
      (_, i) => `• Responsible for project number ${i} across the company`,
    ).join('\n');
    expect(scanResume(text, 3).flagged).toHaveLength(3);
  });

  it('reports a clean resume as clean with nothing flagged', () => {
    const r = scanResume(
      [
        '• Cut p95 latency 38% by caching hot queries',
        '• Shipped a billing rewrite used by 40k customers',
      ].join('\n'),
    );
    expect(r.clean).toBe(true);
    expect(r.empty).toBe(false);
    expect(r.flagged).toEqual([]);
  });

  it('reports text with no bullets as empty, not clean', () => {
    const r = scanResume('Summary\nSkills\nReact TypeScript');
    expect(r.all).toEqual([]);
    expect(r.empty).toBe(true);
    expect(r.clean).toBe(false);
  });

  it('reports arbitrary short text as empty, not clean', () => {
    const r = scanResume('hello world');
    expect(r.empty).toBe(true);
    expect(r.clean).toBe(false);
  });

  it('does not count a numbered-list marker as a metric', () => {
    const r = scanResume('1. Improved the checkout flow for customers');
    expect(r.all[0].flags.map((f) => f.rule)).toContain('no-metric');
  });

  it('detects a repeated verb behind a symbol-font bullet', () => {
    const r = scanResume('\uF0B7 Managed the budget of 4 teams\n\uF0B7 Managed 6 vendors across 3 regions');
    expect(r.all[1].flags.map((f) => f.rule)).toContain('repeated-verb');
  });
});
